async function main() {
  await db.init();

  const apply = process.argv.includes('--apply');
  const existing = managementLog.list({ limit: 2000 });
  const seen = new Set(existing.map(r => `${r.entry_date}::${r.summary}`));

  const toWrite = ENTRIES.filter(e => !seen.has(`${MEETING_DATE}::${e.summary}`));
  const skipped = ENTRIES.length - toWrite.length;

  console.log(`Seed from 1-2-1 ${MEETING_DATE} — ${ENTRIES.length} entries, ${skipped} already present, ${toWrite.length} to write.`);
  console.log(apply ? 'APPLYING.\n' : 'DRY RUN — pass --apply to write.\n');

  for (const e of toWrite) {
    const due = e.dueDate ? ` due ${e.dueDate}` : ' (no due date)';
    console.log(`  [${e.type}] ${e.owner}${e.person ? ` · ${e.person}` : ''}${due} — ${e.summary}`);
    if (apply) {
      managementLog.create({ ...e, entryDate: MEETING_DATE, loggedAt: LOGGED_AT, source: SOURCE });
    }
  }

  if (apply) {
    const a = managementLog.status();
    console.log(`\nLog now holds ${a.totals.rows} rows (${a.totals.open} open).`);
    console.log(`Competency 4 baseline at ${a.baseline.date}: ${a.baseline.count} (${a.baseline.stillOpen} still open). Target 0 by ${a.baseline.targetDate}.`);
    console.log(`Overdue now: ${a.overdueCount}, past the five-working-day standard: ${a.breachesFiveDay.length}.`);
    console.log(`Missing a due date: ${a.missingDue.length} — these need dating with Chris.`);
    console.log(`Not marked as logged in People HR: ${a.hrGap.length}.`);
  }
}

main().catch(e => { console.error(e); process.exit(1); });
