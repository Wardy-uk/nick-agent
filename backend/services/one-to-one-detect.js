function addDays(dateStr, days) {
  const d = new Date(`${dateStr}T12:00:00`); // midday: no DST edge on date-only maths
  d.setDate(d.getDate() + days);
  // Local getters, never toISOString() — see CLAUDE.md.
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

// The cadences NEURO offers, longest name first so "bi-weekly" is matched before
// "weekly" and "bi-monthly" before "monthly" — the old version tested /month/
// first and gave bi-monthly 28 days, i.e. exactly monthly.
const CADENCES = [
  { value: 'bi-monthly', label: 'Bi-monthly (8 weeks)', days: 56, match: /bi[-\s]?month|two[-\s]month/i },
  { value: 'monthly', label: 'Monthly (4 weeks)', days: 28, match: /month/i },
  { value: 'bi-weekly', label: 'Bi-weekly (2 weeks)', days: 14, match: /bi[-\s]?week|fortnight|two[-\s]week/i },
  { value: 'weekly', label: 'Weekly', days: 7, match: /week/i },
];

const DEFAULT_CADENCE_DAYS = 14;

function cadenceDays(cadence) {
  const hit = CADENCES.find(c => c.match.test(String(cadence || '')));
  return hit ? hit.days : DEFAULT_CADENCE_DAYS;
}

/**
 * Stamp each People note with the real last-1-2-1 and the next due date implied
 * by their cadence. Only moves a date FORWARD — a manual entry more recent than
 * anything on disk (a 1-2-1 held but not yet written up) is left alone.
 */
function syncPeopleNotes({ apply = false } = {}) {
  const index = refresh();
  if (!index.ok) return { ok: false, error: index.error, changes: [] };

  const obsidian = require('./obsidian');
  const changes = [];

  for (const person of index.people) {
    const latest = index.byPerson[person.name]?.[0];
    if (!latest) {
      changes.push({ person: person.name, action: 'no-evidence', recorded: person.recordedLast });
      continue;
    }
    if (person.recordedLast && person.recordedLast >= latest.date) {
      // The last-1-2-1 is current, but the due date can still be missing — a
      // note that was off-cadence and came back on it (Maria returning from
      // maternity) has nothing to schedule against, so she would never appear
      // as due and would silently stop being booked. Backfill it.
      if (person.bookable && !person.recordedNextDue) {
        const nextDue = addDays(person.recordedLast, cadenceDays(person.cadence));
        changes.push({ person: person.name, action: 'due-date-backfilled', recorded: person.recordedLast, nextDue });
        if (apply) obsidian.updatePersonNote(person.name, { next121Due: nextDue });
        continue;
      }
      changes.push({ person: person.name, action: 'already-current', recorded: person.recordedLast });
      continue;
    }

    // Only people on an actual cadence get a next due date. cadenceDays() used
    // to fall through to 14 for anything it didn't recognise, which invented a
    // due date for `cadence: n/a` — that put someone on maternity leave into the
    // overdue list and very nearly into a batch booking.
    const next121Due = person.bookable ? addDays(latest.date, cadenceDays(person.cadence)) : null;
    changes.push({
      person: person.name,
      action: 'updated',
      from: person.recordedLast || null,
      to: latest.date,
      nextDue: next121Due,
      bookable: person.bookable,
      evidence: latest.path,
    });

    if (apply) {
      obsidian.updatePersonNote(person.name, {
        last121: latest.date,
        ...(next121Due ? { next121Due } : {}),
      });
    }
  }

  return { ok: true, apply, changes, scanned: index.scanned, skippedPrep: index.skippedPrep };
}

