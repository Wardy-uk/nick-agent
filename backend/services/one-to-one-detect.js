/**
 * Build the name→person map from People notes. Includes `aliases` frontmatter,
 * which is how "Seb"/"Abdi Mohammad" resolve — 17 notes carry it and nothing
 * else in NEURO reads it.
 *
 * A token mapping to more than one person is dropped rather than guessed (the
 * same precision rule vault-hygiene uses for link insertion).
 */
function buildRoster({ includeInactive = false } = {}) {
  const dir = path.join(vaultPath(), 'People');
  if (!fs.existsSync(dir)) return { people: [], tokens: new Map() };

  const people = [];
  const claims = new Map(); // lowercased token -> Set of full names

  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.md')) continue;
    const full = path.join(dir, file);
    let raw;
    try { raw = readNote(full); } catch { continue; }

    const fm = parseFrontmatter(raw);
    const name = file.replace(/\.md$/, '');
    const isReport = String(fm['direct-report'] || '').toLowerCase() === 'true';
    if (!isReport) continue;

    const archived = String(fm['archived'] || '').toLowerCase() === 'true';
    if (archived && !includeInactive) continue;

    const cadence = (fm.cadence || 'fortnightly').toLowerCase().trim();
    const person = {
      name,
      role: fm.role || '',
      cadence,
      status: fm.status || '',
      // Someone off-cadence is still a direct report — they keep their card and
      // their history — but they are never scheduled. To take someone out of the
      // rota (maternity, long-term sick, anything), set `cadence: n/a`.
      bookable: !archived && !NO_CADENCE.test(cadence),
      recordedLast: fm['last-1-2-1'] || null,
      recordedNextDue: fm['next-1-2-1-due'] || null,
      email: fm.email || null,
      archived,
    };
    people.push(person);

    const tokens = new Set([name, name.split(' ')[0]]);
    for (const a of parseListField(raw, 'aliases')) tokens.add(a);
    for (const t of tokens) {
      const key = t.toLowerCase().trim();
      if (!key || key.length < 3) continue;
      if (!claims.has(key)) claims.set(key, new Set());
      claims.get(key).add(name);
    }
  }

  const tokens = new Map();
  for (const [token, owners] of claims) {
    if (owners.size === 1) tokens.set(token, [...owners][0]);
  }
  return { people, tokens };
}

// ---------------------------------------------------------------------------
// Frontmatter helpers (deliberately local — obsidian.js's parser is regex-based
// and does not handle the list forms `people:` and `aliases:` use)
// ---------------------------------------------------------------------------

function frontmatterBlock(content) {
  if (!content.startsWith('---')) return '';
  const end = content.indexOf('\n---', 3);
  return end === -1 ? '' : content.slice(3, end);
}

// Horizontal whitespace only. Plain `\s*` also matches the newline, so on a key
// with an empty value (`people:` followed by an indented list) it ran on into the
// next line and swallowed the first list item.
const HSPACE = '[^\\S\\n]*';

function parseFrontmatter(content) {
  const out = {};
  for (const line of frontmatterBlock(content).split('\n')) {
    const m = line.match(/^([A-Za-z0-9_-]+):[^\S\n]*(.*)$/);
    if (!m) continue;
    out[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

/** Read a YAML list field in either inline (`[a, b]`) or block (`- a`) form. */
function parseListField(content, field) {
  const block = frontmatterBlock(content);
  const re = new RegExp(`^${field}:${HSPACE}(.*)$`, 'm');
  const m = block.match(re);
  if (!m) return [];

  const inline = m[1].trim();
  if (inline.startsWith('[')) {
    return inline.slice(1, -1).split(',').map(cleanToken).filter(Boolean);
  }

  const rest = block.slice(m.index + m[0].length).split('\n');
  const items = [];
  for (const line of rest) {
    if (/^\s*-\s+/.test(line)) items.push(cleanToken(line.replace(/^\s*-\s+/, '')));
    else if (line.trim()) break; // next key ends the list
  }
  return items.filter(Boolean);
}

/** `"[[People/Abdi Mohamed|Abdi Mohamed]]"` -> `Abdi Mohamed` */
function cleanToken(s) {
  return String(s)
    .trim()
    .replace(/^["']|["']$/g, '')
    .replace(/^\[\[|\]\]$/g, '')
    .split('|').pop()
    .split('/').pop()
    .trim();
}

