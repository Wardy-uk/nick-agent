const TITLE_121 = /(^|[^\d-])(1-1|1-2-1|1:1)([^\d-]|$)|one[- ]to[- ]one|one[- ]on[- ]one/i;

/**
 * Is this note a 1-2-1? `meeting-type` is the reliable signal, but older Plaud
 * notes predate the field (Hope's 30 Apr 1-2-1 has no `meeting-type` at all),
 * so fall back to the title. The fallback only opens the gate — attribution
 * still has to pin the note to one person before it counts.
 */
function isOneToOneType(fm, filename) {
  const t = String(fm['meeting-type'] || '').trim().toLowerCase();
  if (t) return t === '1-1' || t === '1-2-1' || t === 'one-to-one' || t === '1:1';
  return TITLE_121.test(String(fm.title || '')) || TITLE_121.test(filename || '');
}

/**
 * Attribute a note to a single person, or null when it can't be pinned down.
 *
 * Frontmatter `people:` links identify the candidate, but they do NOT win on
 * their own — Plaud generates them and they are frequently incomplete. The
 * 4 June "Remote Work Adjustment — Stephen Mitchell, Heidi, Naomi" note links
 * only Stephen, so trusting the links alone filed a three-hander as Stephen's
 * 1-2-1. The body has to agree: whoever is named must also dominate the
 * mentions, which is what actually distinguishes a 1-2-1 from a group meeting.
 */
function attribute(content, roster) {
  // A title that names two or more of the team is a group meeting, full stop —
  // "Remote Work Adjustment & Ticket Quality — Stephen Mitchell, Heidi, Naomi"
  // otherwise squeaked past the mention threshold at exactly 0.60 and became
  // Stephen's 1-2-1.
  const title = String(parseFrontmatter(content).title || '');
  if (title) {
    const named = new Set();
    for (const [token, owner] of roster.tokens) {
      if (countWord(title, token)) named.add(owner);
    }
    if (named.size > 1) return null;
  }

  const linked = parseListField(content, 'people')
    .map(n => roster.tokens.get(n.toLowerCase()))
    .filter(Boolean);
  const distinct = [...new Set(linked)];
  if (distinct.length > 1) return null; // a group meeting, whatever it's tagged

  const counts = new Map();
  for (const [token, owner] of roster.tokens) {
    const hits = countWord(content, token);
    if (hits) counts.set(owner, (counts.get(owner) || 0) + hits);
  }
  const total = [...counts.values()].reduce((a, b) => a + b, 0);
  const shareOf = person => (total ? (counts.get(person) || 0) / total : 0);

  if (distinct.length === 1) {
    const person = distinct[0];
    // No roster member named anywhere: nothing contradicts the link, take it.
    if (!counts.size) return { person, via: 'frontmatter', share: 1 };
    const share = shareOf(person);
    if (share < DOMINANCE) return null; // body disagrees — someone else is all over it
    return { person, via: 'frontmatter', share: Number(share.toFixed(2)) };
  }

  if (!counts.size) return null;
  let best = null;
  for (const [person, n] of counts) {
    if (!best || n > best.n) best = { person, n };
  }
  const share = best.n / total;
  if (best.n < MIN_MENTIONS || share < DOMINANCE) return null;
  return { person: best.person, via: 'mentions', share: Number(share.toFixed(2)) };
}

function countWord(haystack, token) {
  const escaped = token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = haystack.match(new RegExp(`\\b${escaped}\\b`, 'gi'));
  return m ? m.length : 0;
}

// Recording metadata and unfilled template scaffolding — present in every Plaud
// note, so without this the card shows "Location: [Insert Location]" three times
// instead of what was actually discussed.
const BOILERPLATE = /^(plaud id|created|started|duration|device|transcript|date & time|date|time|location|attendees|participants|summary|type)\b\s*:/i;

/** Pull the note's own summary lines, so the card can show substance not just a date. */
function extractHighlights(content, limit = 3) {
  const body = content.replace(/^---[\s\S]*?\n---/, '');
  const out = [];
  for (const line of body.split('\n')) {
    const bullet = line.match(/^\s*[-*]\s+(?!\[[ x]\])(.+)$/);
    if (!bullet) continue;
    let text = bullet[1];
    if (/^\s*\[\d{1,2}:\d{2}(:\d{2})?\]/.test(text)) continue; // transcript speaker line
    text = text.replace(/\[\[([^\]|]*\|)?([^\]]*)\]\]/g, '$2').replace(/[*_`]/g, '').trim();
    if (text.length < 25 || text.length > 200) continue;
    if (BOILERPLATE.test(text)) continue;
    if (/\[insert/i.test(text)) continue; // unfilled template placeholder
    out.push(text);
    if (out.length >= limit) break;
  }
  return out;
}

/**
 * Walk Meetings/ and return every genuine 1-2-1, newest first, grouped by person.
 */
function scan({ includeInactive = false } = {}) {
  const root = vaultPath();
  const meetingsDir = path.join(root, 'Meetings');
  if (!root || !fs.existsSync(meetingsDir)) {
    return { ok: false, error: 'vault or Meetings/ not found', byPerson: {}, scanned: 0 };
  }

  const roster = buildRoster({ includeInactive });
  if (!roster.people.length) {
    return { ok: false, error: 'no direct reports found in People/', byPerson: {}, scanned: 0 };
  }

  const byPerson = {};
  let scanned = 0;
  let skippedPrep = 0;
  let unattributed = 0;

  const walk = (dir, depth) => {
    if (depth > 6) return;
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      if (entry.isDirectory()) {
        if (EXCLUDE_DIRS.has(entry.name)) continue;
        walk(path.join(dir, entry.name), depth + 1);
        continue;
      }
      if (!entry.name.endsWith('.md')) continue;

      const full = path.join(dir, entry.name);
      let content;
      try { content = readNote(full); } catch { continue; }

      const fm = parseFrontmatter(content);
      if (!isOneToOneType(fm, entry.name)) continue;
      scanned++;

      // Rule 1: prep is not evidence a 1-2-1 happened. A transcript is — often
      // the only evidence left, since the Plaud reset archived some summaries
      // and orphaned their transcripts (Hope's 30 Apr 1-2-1 is the case that
      // found this). The bulk transcript mirrors are excluded by directory, so
      // accepting them here recovers orphans without duplicating the tree.
      const noteType = String(fm.type || '').toLowerCase();
      if (noteType !== 'meeting' && noteType !== 'transcript') { skippedPrep++; continue; }

      const who = attribute(content, roster);
      if (!who) { unattributed++; continue; }

      const date = fm.date || (entry.name.match(/^(\d{4}-\d{2}-\d{2})/) || [])[1];
      if (!date) continue;

      (byPerson[who.person] ||= []).push({
        date,
        title: (fm.title || entry.name.replace(/\.md$/, '')).replace(/^\d{2}-\d{2}\s+/, ''),
        path: path.relative(root, full).replace(/\\/g, '/'),
        noteType,
        via: who.via,
        share: who.share,
        highlights: extractHighlights(content),
      });
    }
  };
  walk(meetingsDir, 0);

  for (const person of Object.keys(byPerson)) {
    // One meeting can leave both a summary and a transcript. Same person, same
    // day = same 1-2-1; keep the summary, which is the note of record.
    const seen = new Map();
    for (const item of byPerson[person]) {
      const existing = seen.get(item.date);
      if (!existing || (existing.noteType === 'transcript' && item.noteType === 'meeting')) {
        seen.set(item.date, item);
      }
    }
    const list = [...seen.values()].sort((a, b) => b.date.localeCompare(a.date));
    byPerson[person] = list.slice(0, MAX_PER_PERSON);
  }

  return {
    ok: true,
    byPerson,
    people: roster.people,
    scanned,
    skippedPrep,
    unattributed,
    scannedAt: new Date().toISOString(),
  };
}

// ---------------------------------------------------------------------------
// Cache — the board asks for this on every load; a full Meetings/ walk is ~700
// files over Syncthing, so serve from agent_state and rebuild on the schedule.
// ---------------------------------------------------------------------------

function readCache() {
  try {
    const raw = db.getState(CACHE_KEY);
    return raw ? JSON.parse(raw) : null;
  } catch { return null; }
}

function writeCache(index) {
  // setState takes a primitive — objects must be stringified (see mistakes log).
  try { db.setState(CACHE_KEY, JSON.stringify(index)); } catch (e) {
    console.warn('[1-2-1] Cache write failed:', e.message);
  }
}

function refresh(opts = {}) {
  const index = scan(opts);
  if (index.ok) writeCache(index);
  return index;
}

// A full scan is ~40ms on the Pi, so the cache exists to avoid re-walking
// Meetings/ on every board render, NOT because the scan is expensive. Hold it
// for five minutes: notes arrive by Syncthing, and vault-hooks deliberately do
// not fire for those (see the scheduler's 10pm comment), so a stale-until-2200
// cache would mean a 1-2-1 recorded this morning still showed yesterday's date
// all day. Nightly sync remains the thing that writes People frontmatter.
const CACHE_TTL_MS = 5 * 60 * 1000;

function isStale(index) {
  if (!index?.scannedAt) return true;
  const age = Date.now() - new Date(index.scannedAt).getTime();
  return !Number.isFinite(age) || age < 0 || age > CACHE_TTL_MS;
}

/** Cached index, rebuilding on a cold or stale cache. */
function getIndex({ force = false } = {}) {
  if (force) return refresh();
  const cached = readCache();
  return cached && !isStale(cached) ? cached : refresh();
}

/** The card's payload: the most recent 1-2-1s NEURO can prove happened. */
function getRecent(name, limit = 3) {
  const index = getIndex();
  return (index.byPerson?.[name] || []).slice(0, limit);
}

