'use strict';

/**
 * 1-2-1 detection — works out when Nick last actually HELD a 1-2-1 with each
 * direct report, by reading the meeting notes Syncthing delivers into the vault.
 *
 * Why this exists: `last-1-2-1` in People frontmatter was hand-maintained, so it
 * froze in March 2026 while 1-2-1s carried on being held and recorded. Every
 * consumer downstream (the Team board's overdue badge, the 1-2-1 Tracker, the
 * standup nudge) inherited that stale date, so the board showed people 100+ days
 * overdue who had been seen in July. The dates now come from the notes.
 *
 * Two rules do most of the work:
 *
 *   1. A prep note is NOT a 1-2-1. `type: meeting-prep` notes are generated by
 *      NEURO *before* a 1-2-1 and carry `meeting-type: "1-1"` like the real
 *      thing. Heidi had five of them (Apr→Aug), each generated from the same
 *      stale `last-1-2-1`, none followed by an actual meeting note. Counting
 *      them would mark a 1-2-1 as held purely because NEURO prepped for it —
 *      the exact loop this service exists to break. `type` must be `meeting`.
 *
 *   2. Attribution is dominance-based, not first-name-match. Names get
 *      mentioned in meetings they weren't in. A note counts as X's 1-2-1 only if
 *      X owns most of the mentions (MIN_MENTIONS + DOMINANCE), which correctly
 *      keeps three-hander notes like "Remote Work Adjustment — Stephen, Heidi,
 *      Naomi" (0.55 share) out of anyone's history while accepting a genuine
 *      solo 1-2-1 (0.8+). Frontmatter `people:` links win outright when present.
 *
 * Read-only against Meetings/. The only thing it writes is People frontmatter,
 * and only via syncPeopleNotes().
 */

const fs = require('fs');
const path = require('path');

const db = require('../db/database');

const CACHE_KEY = 'one_to_one_index';
const MIN_MENTIONS = 12;   // below this, a "dominant" name is just noise
const DOMINANCE = 0.6;     // share of mentions needed to own the note
const MAX_PER_PERSON = 5;  // how much history to keep per person

// Whether someone is scheduled is decided by `cadence` alone, never by reading
// the free-text `status`. A first attempt matched /maternity/ against status and
// promptly excluded Maria for the status "Active — returned FROM maternity" —
// prose describing a person is not a flag. `cadence: n/a` is what the vault's
// own 1-2-1 Tracker has always used to mean "exclude", so use exactly that.
const NO_CADENCE = /^(n\/?a|none|-|)$/;

// Generated output and dead copies — scanning these resurrects archived 1-2-1s
// and double-counts Plaud summary variants.
const EXCLUDE_DIRS = new Set([
  'Archive', 'Recycle Bin', '_toDelete', '_Staging - Keep in Archive',
  'transcripts', '_transcripts', 'Vault Audit', '.lint-backups', '.git',
]);

function vaultPath() {
  return process.env.OBSIDIAN_VAULT_PATH || '';
}

/**
 * Read a note with line endings normalised to LF.
 *
 * The vault is authored on Windows, so most notes are CRLF. In JS regex `\r` is
 * a line terminator, which means `.` does not match it and `/^key:\s*(.*)$/`
 * fails on every single CRLF line — the parser silently returned {} and those
 * notes vanished from the scan. Normalise once, here, rather than making every
 * downstream pattern carry an `\r?`.
 */
function readNote(filePath) {
  return fs.readFileSync(filePath, 'utf-8').replace(/\r\n/g, '\n');
}

